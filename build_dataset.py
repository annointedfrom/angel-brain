#!/usr/bin/env python3
"""build_dataset.py - turn the vault into QLoRA training data (JSONL).

Runs on CPU (no training stack needed). Two modes:
  raw : {"text": <chunk>}                          (completion / style)
  qa  : {"instruction": <Q>, "input": "", "output": <chunk>}
        where Q is generated by a LOCAL Ollama model from the chunk (self-instruct).

See SPEC.md. Excludes Ideas/ (sacred) and Archive/ by default.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.request

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

OLLAMA = os.environ.get("OLLAMA_URL", "http://localhost:11434")
TEXT_EXT = {".md", ".markdown", ".txt"}
DEFAULT_EXCLUDE = [".git", ".obsidian", "node_modules", "__pycache__", ".remember", "Archive", "Ideas"]

QGEN_SYSTEM = (
    "You write ONE natural question that the following note would be the ideal answer to. "
    "Reply with only the question, no preamble, no quotes."
)


def collect_files(paths: list[str], excludes: list[str]) -> list[str]:
    found: list[str] = []
    for p in paths:
        if os.path.isfile(p) and os.path.splitext(p)[1].lower() in TEXT_EXT:
            found.append(p)
        elif os.path.isdir(p):
            for root, dirs, files in os.walk(p):
                dirs[:] = [d for d in dirs if d not in excludes]
                for f in files:
                    fp = os.path.join(root, f)
                    if os.path.splitext(f)[1].lower() in TEXT_EXT and not any(x in fp for x in excludes):
                        found.append(fp)
    return sorted(set(found))


def _strip_frontmatter(text: str) -> str:
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            return text[end + 4:]
    return text


def chunk_text(text: str, chunk_chars: int) -> list[str]:
    paras = [p.strip() for p in _strip_frontmatter(text).split("\n\n") if p.strip()]
    chunks, buf = [], ""
    for para in paras:
        if len(buf) + len(para) + 2 <= chunk_chars:
            buf = f"{buf}\n\n{para}" if buf else para
        else:
            if buf:
                chunks.append(buf)
            buf = para
    if buf:
        chunks.append(buf)
    return [c for c in chunks if len(c) >= 80]


def gen_question(chunk: str, model: str) -> str | None:
    prompt = f"{QGEN_SYSTEM}\n\n=== Note ===\n{chunk}\n\n=== Question ==="
    body = json.dumps({
        "model": model, "prompt": prompt, "stream": False, "think": False,
        "options": {"num_ctx": 8192, "temperature": 0.6},
    }).encode()
    req = urllib.request.Request(
        f"{OLLAMA}/api/generate", data=body, headers={"Content-Type": "application/json"}, method="POST"
    )
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            q = (json.loads(r.read()).get("response") or "").strip()
        return q.splitlines()[0].strip().strip('"') if q else None
    except (urllib.error.URLError, OSError, ValueError) as e:
        print(f"  [qgen] failed ({e})", file=sys.stderr)
        return None


def main() -> None:
    ap = argparse.ArgumentParser(description="Build QLoRA training JSONL from the vault.")
    ap.add_argument("paths", nargs="+", help="Files/folders (.md/.txt).")
    ap.add_argument("-o", "--out", default="data.jsonl", help="Output JSONL path.")
    ap.add_argument("--mode", choices=("raw", "qa"), default="qa", help="raw=completion, qa=instruction pairs.")
    ap.add_argument("--model", default="nemotron-3-nano:4b", help="Local model for qa question-gen.")
    ap.add_argument("--exclude", nargs="*", default=DEFAULT_EXCLUDE, help="Path fragments to skip.")
    ap.add_argument("--chunk-chars", type=int, default=1000, help="Target chunk size.")
    ap.add_argument("--limit", type=int, default=0, help="Max examples (0 = all).")
    args = ap.parse_args()

    files = collect_files(args.paths, args.exclude)
    chunks: list[tuple[str, str]] = []
    for fp in files:
        try:
            raw = open(fp, encoding="utf-8", errors="replace").read()
        except OSError:
            continue
        for ch in chunk_text(raw, args.chunk_chars):
            chunks.append((os.path.relpath(fp), ch))
    if args.limit:
        chunks = chunks[: args.limit]
    print(f"{len(files)} files -> {len(chunks)} chunks (mode={args.mode}, model={args.model if args.mode=='qa' else '-'})")

    written = 0
    with open(args.out, "w", encoding="utf-8") as out:
        for i, (rel, ch) in enumerate(chunks):
            if args.mode == "raw":
                rec = {"text": ch, "source": rel}
            else:
                q = gen_question(ch, args.model)
                if not q:
                    continue
                rec = {"instruction": q, "input": "", "output": ch, "source": rel}
            out.write(json.dumps(rec, ensure_ascii=False) + "\n")
            written += 1
            if written % 10 == 0 or written == len(chunks):
                print(f"  [{written}] {rel}")
    print(f"Wrote {written} examples -> {args.out}")


if __name__ == "__main__":
    main()
